export function drawingWords(items){
 const chosen=new Map();
 for(const item of items){
  const word=item.front?.trim().toLowerCase();
  if(item.type==='word'&&objects.has(word))chosen.set(word,{...item,front:word,back:objects.get(word)});
 }
 return chosen.size?[...chosen.values()]:[...objects].map(([front,back])=>({type:'word',front,back}));
}
